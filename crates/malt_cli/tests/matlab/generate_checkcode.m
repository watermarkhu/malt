%GENERATE_CHECKCODE Run MATLAB's Code Analyzer over the conformance fixtures, as a TSV.
%   Phase 1 of the live checkcode check (tests/matlab_live.rs does phase 2). CI runs it with
%   matlab-actions/run-command, the licensed way to run MATLAB on a public repository:
%
%       run('crates/malt_cli/tests/matlab/generate_checkcode.m')
%
%   The test runs the same script when it has to start MATLAB itself. No arguments. Environment:
%     MALT_CHECKCODE_OUT   the TSV file to write
%                          (default: <repo>/target/matlab/checkcode.tsv)
%   Next to it, <stem>.release holds version('-release') (for checkcode.tsv: checkcode.release).
%
%   The TSV has the columns of tests/fixtures/matlab_expected.tsv: path relative to the fixtures
%   folder (forward slashes), line (0 becomes 1, as the expectations do) and check ID. checkcode
%   runs with its default configuration, as matlab_probe.m does.
%   A file that checkcode fails on is written as the ID PROBE_ERROR, so it shows as a difference.
%
%   Beside the TSV, in the same folder:
%     checkcode_messages.tsv  path, line, ID and MATLAB's message text (tabs and line breaks
%                             become spaces). MathWorks content: under target/ only, never
%                             committed. tests/matlab_live.rs compares it with malt's messages.
%     checkcode_files.txt     every file that was checked, one relative path per line: the
%                             list tests/fixtures/matlab_files.txt must equal.

here = fileparts(mfilename('fullpath'));
repo = fileparts(fileparts(fileparts(fileparts(here))));
fixtures = fullfile(repo, 'crates', 'malt_cli', 'tests', 'fixtures');

out = getenv('MALT_CHECKCODE_OUT');
if isempty(out)
    out = fullfile(repo, 'target', 'matlab', 'checkcode.tsv');
end
if ~isfolder(fileparts(out))
    mkdir(fileparts(out));
end
[outFolder, outStem] = fileparts(out);
releaseFile = fullfile(outFolder, [outStem '.release']);

% Every .m file under the fixtures, at any depth: the same set the conformance test reads.
files = sort(listMfiles(fixtures, ''));

release = version('-release');
rf = fopen(releaseFile, 'w', 'n', 'UTF-8');
if rf < 0
    error('generate_checkcode:release', 'cannot write %s', releaseFile);
end
fprintf(rf, '%s\n', release);
fclose(rf);

fid = fopen(out, 'w', 'n', 'UTF-8');
if fid < 0
    error('generate_checkcode:open', 'cannot write %s', out);
end
cleaner = onCleanup(@() fclose(fid));
fprintf(fid, '# What MATLAB %s checkcode reports for the fixture files: path, line, check ID.\n', release);
fprintf(fid, '# Generated by generate_checkcode.m (live check). Not committed.\n');

messagesFile = fullfile(outFolder, 'checkcode_messages.tsv');
fm = fopen(messagesFile, 'w', 'n', 'UTF-8');
if fm < 0
    error('generate_checkcode:open', 'cannot write %s', messagesFile);
end
cleanerM = onCleanup(@() fclose(fm));
fprintf(fm, '# What MATLAB %s checkcode says for each finding: path, line, check ID, message.\n', release);
fprintf(fm, '# Generated by generate_checkcode.m (live check). MathWorks content: not committed.\n');

filesFile = fullfile(outFolder, 'checkcode_files.txt');
ff = fopen(filesFile, 'w', 'n', 'UTF-8');
if ff < 0
    error('generate_checkcode:open', 'cannot write %s', filesFile);
end
cleanerF = onCleanup(@() fclose(ff));

findings = 0;
errors = 0;
for k = 1:numel(files)
    rel = files{k};
    fprintf(ff, '%s\n', rel);
    try
        info = checkcode(fullfile(fixtures, strrep(rel, '/', filesep)), '-id', '-struct');
    catch err
        errors = errors + 1;
        fprintf('checkcode failed on %s: %s\n', rel, strrep(err.message, newline, ' '));
        fprintf(fid, '%s\t1\tPROBE_ERROR\n', rel);
        continue
    end
    for m = 1:numel(info)
        line = max(1, info(m).line(1));
        fprintf(fid, '%s\t%d\t%s\n', rel, line, info(m).id);
        fprintf(fm, '%s\t%d\t%s\t%s\n', rel, line, info(m).id, oneLine(info(m).message));
        findings = findings + 1;
    end
end
fprintf('checkcode: %d files, %d findings, %d error(s); MATLAB %s; written to %s\n', ...
    numel(files), findings, errors, release, out);

function files = listMfiles(folder, rel)
%LISTMFILES The .m files under folder, as paths relative to it (forward slashes).
files = {};
entries = dir(folder);
for k = 1:numel(entries)
    name = entries(k).name;
    if any(strcmp(name, {'.', '..'}))
        continue
    end
    if isempty(rel)
        child = name;
    else
        child = [rel '/' name];
    end
    if entries(k).isdir
        files = [files, listMfiles(fullfile(folder, name), child)]; %#ok<AGROW>
    else
        [~, ~, ext] = fileparts(name);
        if strcmp(ext, '.m')
            files{end+1} = child; %#ok<AGROW>
        end
    end
end
end

function text = oneLine(text)
%ONELINE A message on one line: tabs and line breaks become spaces.
text = strrep(strrep(strrep(text, sprintf('\r\n'), ' '), newline, ' '), sprintf('\t'), ' ');
end
