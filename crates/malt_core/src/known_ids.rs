/// The entities the naming engine checks (`naming.<entity>.<check>`).
const NAMING_ENTITIES: &[&str] = &[
    "class",
    "enumeration",
    "event",
    "function",
    "localFunction",
    "method",
    "nestedFunction",
    "property",
    "variable",
];

/// The checks of the naming engine (the last part of `naming.<entity>.<check>`).
const NAMING_CHECKS: &[&str] = &[
    "casing",
    "disallowedPhrase",
    "disallowedPrefix",
    "disallowedSuffix",
    "maxLength",
    "minLength",
    "regularExpression",
    "requiredPrefix",
    "requiredSuffix",
];

/// Whether `id` is a check ID MATLAB knows, so that a directive naming it is not
/// an MSNE: a listed ID, or a `naming.<entity>.<check>` ID.
pub fn is_known_check_id(id: &str) -> bool {
    if KNOWN_CHECK_IDS.contains(&id) {
        return true;
    }
    let mut parts = id.split('.');
    matches!(
        (parts.next(), parts.next(), parts.next(), parts.next()),
        (Some("naming"), Some(entity), Some(check), None)
            if NAMING_ENTITIES.contains(&entity) && NAMING_CHECKS.contains(&check)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn listed_and_naming_ids_are_known() {
        assert!(is_known_check_id("NASGU"));
        assert!(is_known_check_id("MSNE"));
        assert!(is_known_check_id("naming.variable.maxLength"));
        assert!(is_known_check_id("naming.class.casing"));
    }

    #[test]
    fn other_ids_are_not_known() {
        assert!(!is_known_check_id("NOSUCHID"));
        assert!(!is_known_check_id("nasgu"));
        assert!(!is_known_check_id(" NASGU "));
        assert!(!is_known_check_id("naming.variable.nosuch"));
        assert!(!is_known_check_id("naming.nothing.casing"));
        assert!(!is_known_check_id(""));
    }
}
